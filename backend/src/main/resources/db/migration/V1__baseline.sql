-- Baseline: the schema Hibernate generated (ddl-auto=update) before Flyway was introduced.
-- Existing databases skip this file (spring.flyway.baseline-version=1); fresh databases run it.
-- Written to be valid on both PostgreSQL and H2 (MODE=PostgreSQL).

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    email VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    color VARCHAR(255),
    icon VARCHAR(255),
    name VARCHAR(255) NOT NULL,
    user_id BIGINT,
    CONSTRAINT fk_categories_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount NUMERIC(38, 2) NOT NULL,
    category_id BIGINT,
    created_at TIMESTAMP(6),
    date DATE NOT NULL,
    description VARCHAR(255) NOT NULL,
    notes VARCHAR(255),
    updated_at TIMESTAMP(6),
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_expenses_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT fk_expenses_user FOREIGN KEY (user_id) REFERENCES users (id)
);
